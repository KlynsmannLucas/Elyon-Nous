const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {PGlite}=require(process.env.PGLITE_MODULE||'@electric-sql/pglite')
const A='00000000-0000-4000-8000-000000000001',B='00000000-0000-4000-8000-000000000002',J='00000000-0000-4000-8000-000000000003'
test('internal service grants and Studio receipts enforce ownership, atomic debits, completed results and refunds',async()=>{
 const db=new PGlite()
 try{
  await db.exec('CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role BYPASSRLS;CREATE TABLE clients(id uuid PRIMARY KEY,user_id text NOT NULL,UNIQUE(id,user_id));')
  for(const file of ['20261110_atomic_credits.sql','20261111205409_internal_reportei_studio.sql'])await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations',file),'utf8'))
  await db.query('INSERT INTO clients VALUES ($1,$2),($3,$4)',[A,'A',B,'B'])
  await db.exec("INSERT INTO reportei_service_config(company_id,company_name,updated_by) VALUES (1,'Company','admin');SET ROLE service_role")
  await assert.rejects(db.query("INSERT INTO reportei_service_links(user_id,client_id,company_id,project_id,project_name,timezone,integration_ids,grant_type,granted_by) VALUES ('A',$1,1,2,'Project','America/Sao_Paulo',ARRAY[3],'administrator','admin')",[B]),/foreign key/)
  const brief={mode:'campaign',formats:['feed','story']}
  await db.query("INSERT INTO studio_jobs(id,user_id,client_id,request_id,brief) VALUES ($1,'A',$2,$1,$3)",[J,A,JSON.stringify(brief)])
  const charge=(step,cost,operation,user='A')=>db.query('SELECT elyon_studio_charge_step($1,$2,$3,15,$4,$5) r',[user,J,step,cost,operation]).then(result=>result.rows[0].r)
  await assert.rejects(charge('plan',4,'campaign_generate','B'),/Job not found/)
  await assert.rejects(charge('plan',1,'campaign_generate'),/Invalid planning charge/)
  await assert.rejects(charge('image:landscape',5,'assets_generate'),/Invalid image charge/)
  const plans=await Promise.all(Array.from({length:8},()=>charge('plan',4,'campaign_generate')))
  assert.equal(new Set(plans.map(r=>r.chargeId)).size,1)
  assert.equal((await db.query("SELECT used FROM ai_credits WHERE user_id='A'")).rows[0].used,4)
  await db.query("SELECT elyon_studio_complete_step('A',$1,'plan',$2)",[J,JSON.stringify({original:true})])
  await db.query("SELECT elyon_studio_complete_step('A',$1,'plan',$2)",[J,JSON.stringify({overwrite:true})])
  assert.equal((await db.query('SELECT plan FROM studio_jobs WHERE id=$1',[J])).rows[0].plan.original,true)
  await db.query("SELECT elyon_studio_fail_step('A',$1,'plan')",[J])
  assert.equal((await db.query("SELECT used FROM ai_credits WHERE user_id='A'")).rows[0].used,4)
  const first=await charge('image:feed',5,'assets_generate')
  await db.query("SELECT elyon_studio_fail_step('B',$1,'image:feed')",[J])
  assert.equal((await db.query("SELECT used FROM ai_credits WHERE user_id='A'")).rows[0].used,9)
  await db.query("SELECT elyon_studio_fail_step('A',$1,'image:feed')",[J]);await db.query("SELECT elyon_studio_fail_step('A',$1,'image:feed')",[J])
  assert.equal((await db.query("SELECT used FROM ai_credits WHERE user_id='A'")).rows[0].used,4)
  const retry=await charge('image:feed',5,'assets_generate');assert.notEqual(first.chargeId,retry.chargeId)
  await charge('image:story',5,'assets_generate')
  await assert.rejects(db.query("INSERT INTO studio_assets(user_id,client_id,job_id,name,kind,format,storage_path,mime_type,width,height) VALUES ('B',$1,$2,'Wrong owner','generated','feed','B/wrong.png','image/png',1080,1350)",[B,J]),/foreign key/)
  await assert.rejects(db.query("SELECT elyon_studio_complete_step('A',$1,'image:feed',$2)",[J,JSON.stringify({assetId:B})]),/Asset not found/)
  assert.equal((await db.query("SELECT used FROM ai_credits WHERE user_id='A'")).rows[0].used,14)
  for(const role of ['anon','authenticated']){
   await db.exec(`RESET ROLE;SET ROLE ${role}`)
   for(const table of ['reportei_service_config','reportei_service_links','reportei_service_snapshots','studio_jobs','studio_assets','studio_steps','studio_publications'])await assert.rejects(db.query(`SELECT * FROM ${table}`),/permission denied/)
   await assert.rejects(charge('plan',4,'campaign_generate'),/permission denied/)
  }
 }finally{await db.close()}
})
